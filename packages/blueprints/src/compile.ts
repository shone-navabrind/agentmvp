import type { Graph, NodeSpec, Edge } from "@harness/flow";
import { KernelError } from "@harness/kernel";
import type { Blueprint } from "./schema.ts";
import { requirementsOf } from "./validate.ts";

/** What the project supplies to fill a blueprint's slots. */
export type Bindings = {
  inputs: Record<string, string>;
  /** seed id -> uploaded artifact reference (object-store key), or null if skipped. */
  seeds: Record<string, string | null>;
  /** repo slot id -> repo names attached to it. */
  repos: Record<string, string[]>;
};

export class BindingsIncomplete extends KernelError {
  constructor(missing: { inputs: string[]; seeds: string[]; repos: string[] }) {
    const parts = [
      missing.inputs.length ? `inputs: ${missing.inputs.join(", ")}` : "",
      missing.seeds.length ? `uploads: ${missing.seeds.join(", ")}` : "",
      missing.repos.length ? `repos: ${missing.repos.join(", ")}` : "",
    ].filter(Boolean);
    super("BINDINGS_INCOMPLETE", `Still needed before setup can start — ${parts.join("; ")}`, { missing }, false);
  }
}

export function checkBindings(bp: Blueprint, b: Bindings): { ok: boolean; missing: ReturnType<typeof requirementsOf> } {
  const req = requirementsOf(bp);
  const missing = {
    inputs: req.inputs.filter((k) => !b.inputs[k]?.trim()),
    seeds: req.seeds.filter((id) => !b.seeds[id]),
    repos: req.repos.filter((id) => !(b.repos[id]?.length)),
  };
  return { ok: !missing.inputs.length && !missing.seeds.length && !missing.repos.length, missing };
}

/** Substitute ${input.X} / ${seed.X} / ${repo.X} against the bindings. */
export function interpolate(value: string, bp: Blueprint, b: Bindings): string {
  return value.replace(/\$\{(input|seed|repo)\.([A-Za-z][A-Za-z0-9_-]*)\}/g, (_m, kind, name) => {
    if (kind === "input") return b.inputs[name] ?? bp.inputs.find((i) => i.key === name)?.default ?? "";
    if (kind === "seed") return b.seeds[name] ?? "";
    return (b.repos[name] ?? []).join(",");
  });
}

/**
 * Render docker compose. Compose is the universal substrate: a curated Odoo stack and a
 * stack a user described in a sentence both land here, so there is one thing to debug.
 */
export function renderCompose(bp: Blueprint, b: Bindings, opts: { portBase: number }): string {
  const lines: string[] = ["# generated by harness-cloud — do not edit by hand", "services:"];
  let portCursor = opts.portBase;

  for (const svc of bp.services) {
    lines.push(`  ${svc.name}:`);
    lines.push(`    image: ${svc.image}`);
    if (svc.command) lines.push(`    command: ${JSON.stringify(interpolate(svc.command, bp, b))}`);
    lines.push("    restart: unless-stopped");

    const env = Object.entries(svc.env);
    if (env.length) {
      lines.push("    environment:");
      for (const [k, v] of env) lines.push(`      ${k}: ${JSON.stringify(interpolate(v, bp, b))}`);
    }
    if (svc.ports.length) {
      lines.push("    ports:");
      for (const p of svc.ports) {
        const host = p.host ?? portCursor++;
        lines.push(`      - "${host}:${p.container}"`);
      }
    }
    if (svc.volumes.length) {
      lines.push("    volumes:");
      for (const v of svc.volumes) lines.push(`      - ${JSON.stringify(interpolate(v, bp, b))}`);
    }
    if (svc.dependsOn.length) {
      lines.push("    depends_on:");
      for (const d of svc.dependsOn) {
        // Wait for health, not just for the container to exist: the most common
        // "it works on the second try" bug in generated compose files.
        const dep = bp.services.find((x) => x.name === d);
        lines.push(`      ${d}:`);
        lines.push(`        condition: ${dep?.healthcheck ? "service_healthy" : "service_started"}`);
      }
    }
    if (svc.healthcheck) {
      lines.push("    healthcheck:");
      lines.push(`      test: ${JSON.stringify(["CMD-SHELL", svc.healthcheck.test])}`);
      lines.push(`      interval: ${svc.healthcheck.intervalSec}s`);
      lines.push(`      timeout: ${svc.healthcheck.timeoutSec}s`);
      lines.push(`      retries: ${svc.healthcheck.retries}`);
    }
  }
  return lines.join("\n") + "\n";
}

/** The port the preview opens by default. */
export function primaryPort(bp: Blueprint, portBase: number): number | null {
  let cursor = portBase;
  for (const svc of bp.services) {
    for (const p of svc.ports) {
      const host = p.host ?? cursor++;
      if (p.primary) return host;
    }
  }
  return null;
}

/**
 * Compile a blueprint into a provisioning graph.
 *
 * Provisioning is not a bespoke state machine: it is an ordinary flow run on the kernel's
 * durable step runtime. That buys crash recovery, memoised steps, a visible timeline and
 * human-in-the-loop gates for free, and it means one engine to reason about.
 */
export function compileProvisioning(bp: Blueprint, b: Bindings): Graph {
  const check = checkBindings(bp, b);
  if (!check.ok) throw new BindingsIncomplete(check.missing);

  const nodes: NodeSpec[] = [];
  const edges: Edge[] = [];
  let prev: string | null = null;
  const link = (id: string) => {
    if (prev) edges.push({ from: prev, to: id });
    prev = id;
  };

  nodes.push({
    id: "acquire",
    type: "provision.acquire-sandbox",
    config: { sandbox: bp.sandbox },
    input: { blueprintId: bp.id },
  });
  prev = "acquire";

  if (bp.repos.length) {
    nodes.push({
      id: "repos",
      type: "provision.attach-repos",
      config: { slots: bp.repos },
      input: { sandboxId: "$.nodes.acquire.sandboxId", repos: b.repos },
    });
    link("repos");
  }

  nodes.push({
    id: "compose",
    type: "provision.write-compose",
    config: { blueprintId: bp.id },
    input: { sandboxId: "$.nodes.acquire.sandboxId" },
  });
  link("compose");

  // Seeds restore before services take traffic, and neutralisation runs inside the same
  // step so a production dump is never readable by the agent in its original form.
  for (const seed of bp.seeds) {
    if (!b.seeds[seed.id]) continue;
    nodes.push({
      id: `seed-${seed.id}`,
      type: "provision.restore-seed",
      config: { seed },
      input: {
        sandboxId: "$.nodes.acquire.sandboxId",
        artifact: b.seeds[seed.id],
      },
    });
    link(`seed-${seed.id}`);
  }

  for (const step of bp.setup) {
    nodes.push({
      id: `setup-${step.id}`,
      type: "provision.run-step",
      config: { step },
      input: { sandboxId: "$.nodes.acquire.sandboxId" },
    });
    link(`setup-${step.id}`);
  }

  nodes.push({
    id: "start",
    type: "provision.start-services",
    config: { services: bp.services.map((s) => s.name) },
    input: { sandboxId: "$.nodes.acquire.sandboxId" },
  });
  link("start");

  nodes.push({
    id: "verify",
    type: "provision.verify",
    config: { checks: bp.verify },
    input: { sandboxId: "$.nodes.acquire.sandboxId" },
  });
  link("verify");

  nodes.push({
    id: "bundles",
    type: "provision.apply-bundles",
    config: { bundles: bp.bundles },
    input: { sandboxId: "$.nodes.acquire.sandboxId" },
  });
  link("bundles");

  return {
    name: `provision-${bp.id}`,
    entry: "acquire",
    nodes,
    edges,
    // A provisioning run that loops is a bug; these are belt and braces.
    guards: { maxSteps: nodes.length + 4, maxWallClockMs: 45 * 60 * 1000 },
    output: {
      sandboxId: "$.nodes.acquire.sandboxId",
      verified: "$.nodes.verify.passed",
      previewPort: "$.nodes.start.previewPort",
    },
  };
}

/** Plain-language progress labels, for the non-technical view of the same run. */
export function friendlyStepLabels(bp: Blueprint): Record<string, string> {
  const out: Record<string, string> = {
    acquire: "Setting up your private machine",
    repos: "Connecting your code",
    compose: "Describing the services",
    start: "Starting everything up",
    verify: "Checking it actually works",
    bundles: "Teaching the assistant about your stack",
  };
  for (const s of bp.seeds) out[`seed-${s.id}`] = `Loading ${s.label.toLowerCase()}`;
  for (const s of bp.setup) out[`setup-${s.id}`] = bp.ui.friendlySteps[s.id] ?? s.label;
  return out;
}
